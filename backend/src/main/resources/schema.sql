CREATE TABLE users (id BIGINT PRIMARY KEY, name VARCHAR(80) NOT NULL, token VARCHAR(80) UNIQUE NOT NULL, points INT NOT NULL CHECK (points >= 0));
CREATE TABLE rooms (id BIGINT PRIMARY KEY, name VARCHAR(80) NOT NULL, capacity INT NOT NULL, hourly_price INT NOT NULL);
CREATE TABLE reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id), room_id BIGINT NOT NULL REFERENCES rooms(id),
 start_at TIMESTAMP WITH TIME ZONE NOT NULL, end_at TIMESTAMP WITH TIME ZONE NOT NULL,
 total_price INT NOT NULL CHECK (total_price >= 0), points_used INT NOT NULL CHECK (points_used >= 0),
 status VARCHAR(20) NOT NULL CHECK (status IN ('CONFIRMED', 'CANCELLED'))
);
